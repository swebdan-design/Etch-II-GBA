def emit(f, name, font, h):
    widths, rows = [], []
    for c in range(32, 96):
        g = font.get(chr(c), font['?'])
        assert len(g) == h, chr(c)
        w = len(g[0])
        assert all(len(r) == w for r in g), chr(c)
        widths.append(w)
        for r in g:
            b = 0
            for x, ch in enumerate(r):
                if ch == '#':
                    b |= 0x80 >> x
            rows.append(b)
    f.write("const uint8_t %s_w[64] = { %s };\n" % (name, ", ".join(map(str, widths))))
    f.write("const uint8_t %s_rows[%d] = {\n" % (name, len(rows)))
    for i in range(0, len(rows), h * 4):
        f.write("    " + ", ".join("0x%02X" % b for b in rows[i:i + h * 4]) + ",\n")
    f.write("};\n\n")


def main():
    import sys
    path = sys.argv[1]
    with open(path, "w") as f:
        f.write("/* AUTOGENERATED by tools/gen_fonts.py -- do not edit. */\n#include <stdint.h>\n\n")
        f.write("/* small: 3x5 caps (5 rows per glyph); main: 5x7 rounded caps (7 rows) */\n")
        emit(f, "font_small", SMALL, 5)
        emit(f, "font_main", MAIN, 7)
    print("wrote", path)


if __name__ == "__main__":
    main()
