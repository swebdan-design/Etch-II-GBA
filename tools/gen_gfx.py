tiles = [[[2] * 8 for _ in range(8)] for _ in range(256)]   # 2 = background colour


def glyph(code, rows):
    t = [[2] * 8 for _ in range(8)]
    for y, row in enumerate(rows.split("|")):
        for x, ch in enumerate(row):
            if ch == "#":
                t[y][x + 1] = 1
    tiles[code] = t


for ch, rows in F.items():
    glyph(ord(ch), rows)


def pix(code, art, fg=1, bg=2):
    t = [[bg] * 8 for _ in range(8)]
    for y, row in enumerate(art.split("|")):
        for x, ch in enumerate(row):
            if ch == "#":
                t[y][x] = fg
            elif ch == "o":
                t[y][x] = 3
    tiles[code] = t


